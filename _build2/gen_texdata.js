/* Generates _build2/parts/s20_texdata.js — embedded texture data URIs.
   Sources: Polyhaven CC0 (downloaded+re-encoded in tex_out/) and Kenney CC0 retro set. */
const fs = require('fs');
const path = require('path');
const root = __dirname;
const outDir = path.join(root, 'tex_out');
const kenney = path.join(root, '..', 'kenney_retro-textures-fantasy', 'PNG');

const items = {
  asp_d: ['jpg', path.join(outDir, 'asp_d.jpg')],
  asp_n: ['jpg', path.join(outDir, 'asp_n.jpg')],
  asp_r: ['jpg', path.join(outDir, 'asp_r.jpg')],
  pv_d:  ['jpg', path.join(outDir, 'pv_d.jpg')],
  pv_n:  ['jpg', path.join(outDir, 'pv_n.jpg')],
  gr_d:  ['jpg', path.join(outDir, 'gr_d.jpg')],
  gr_n:  ['jpg', path.join(outDir, 'gr_n.jpg')],
  dg_d:  ['jpg', path.join(outDir, 'dg_d.jpg')],
  dg_n:  ['jpg', path.join(outDir, 'dg_n.jpg')],
  k_planks: ['png', path.join(kenney, 'floor_wood_planks_wide.png')],
  k_tiles:  ['png', path.join(kenney, 'floor_tiles_tan_large.png')],
  dnm_d: ['jpg', path.join(outDir, 'dnm_d.jpg')],
  dnm_n: ['jpg', path.join(outDir, 'dnm_n.jpg')],
  jrs_d: ['jpg', path.join(outDir, 'jrs_d.jpg')],
  jrs_n: ['jpg', path.join(outDir, 'jrs_n.jpg')],
  lin_d: ['jpg', path.join(outDir, 'lin_d.jpg')],
  lin_n: ['jpg', path.join(outDir, 'lin_n.jpg')],
  ltr_d: ['jpg', path.join(outDir, 'ltr_d.jpg')],
  ltr_n: ['jpg', path.join(outDir, 'ltr_n.jpg')],
  rub_d: ['jpg', path.join(outDir, 'rub_d.jpg')],
  rub_n: ['jpg', path.join(outDir, 'rub_n.jpg')],
};

let js = '/* ============================================================\n'
       + '   PART 20: TEXTURE PAYLOAD (generated by gen_texdata.js)\n'
       + '   Polyhaven CC0 photoscans + Kenney CC0 retro set, embedded\n'
       + '   as data URIs so the game stays a single self-contained file.\n'
       + '   ============================================================ */\n'
       + 'window.SA_TEX = {';
let total = 0;
for (const k in items) {
  const [ext, file] = items[k];
  if (!fs.existsSync(file)) { console.error('MISSING', file); process.exit(1); }
  const b = fs.readFileSync(file);
  total += b.length;
  js += '\n  ' + k + ':"data:image/' + ext + ';base64,' + b.toString('base64') + '",';
}
js += '\n};\n';
const out = path.join(root, 'parts', 's20_texdata.js');
fs.writeFileSync(out, js, { encoding: 'utf8' });
console.log('s20_texdata.js written:', (fs.statSync(out).size / 1024 / 1024).toFixed(2), 'MB  (raw assets', (total / 1024).toFixed(0), 'KB)');
